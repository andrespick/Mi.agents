#!/usr/bin/env python3
"""Mi.agents: plan first, render native adapters, back up exact bytes. Python 3.11+."""
import argparse
import base64
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile
import tomllib
import uuid

OWNER = 'Generated by Mi.agents; edit the source library and reinstall.'
BEGIN = '# BEGIN MI.AGENTS MANAGED'
END = '# END MI.AGENTS MANAGED'
MD_BEGIN = '<!-- BEGIN MI.AGENTS MANAGED -->'
MD_END = '<!-- END MI.AGENTS MANAGED -->'
NAME = re.compile(r'^[a-z0-9]+(?:-[a-z0-9]+)*$')
PROFILES = ('simple', 'development', 'security')


def read_bytes(path):
    return path.read_bytes() if path.exists() else None


def read_text(path):
    return (read_bytes(path) or b'').decode('utf-8-sig')


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def digest(value):
    return hashlib.sha256(value).hexdigest() if value is not None else None


def check_path(path):
    """Do not follow destination symlinks/junctions, including parent directories."""
    for part in (path, *path.parents):
        try:
            info = part.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, 'st_file_attributes', 0) & getattr(stat, 'FILE_ATTRIBUTE_REPARSE_POINT', 0x400):
            raise ValueError(f'Conflicto: destino o padre enlazado, revíselo manualmente: {part}')


def load_catalog(root):
    return json.loads(read_text(root / 'agents/catalog.json'))['agents']


def validate_library(root):
    issues = []
    names = set()
    for folder in sorted((root / 'skills').iterdir()):
        if not folder.is_dir() or folder.name.startswith('.'):
            continue
        text = read_text(folder / 'SKILL.md')
        names.add(folder.name)
        header = text.split('---', 2)[1] if text.startswith('---') and text.count('---') >= 2 else ''
        if not NAME.fullmatch(folder.name) or not re.search(r'(?m)^name: ' + re.escape(folder.name) + r'\r?$', header):
            issues.append(f'Nombre no portable o frontmatter distinto: {folder.name}')
        for expected in ('disable-model-invocation: true', 'opencode/autoinvoke: "false"', 'opencode/slash: "true"'):
            if expected not in header:
                issues.append(f'Falta metadata manual {expected}: {folder.name}')
        if 'allow_implicit_invocation: false' not in read_text(folder / 'agents/openai.yaml'):
            issues.append(f'Falta política Codex: {folder.name}')
    agents = load_catalog(root)
    agent_names = [a['name'] for a in agents]
    if len(set(agent_names)) != len(agent_names):
        issues.append('Nombres de agentes duplicados')
    for agent in agents:
        if not NAME.fullmatch(agent['name']):
            issues.append(f'Nombre de agente inválido: {agent["name"]}')
        if agent['access'] not in ('read', 'report', 'development'):
            issues.append(f'Acceso desconocido: {agent["name"]}')
        path = (root / 'agents' / agent['instructions']).resolve()
        if not path.is_relative_to((root / 'agents').resolve()) or not path.is_file():
            issues.append(f'Instrucciones inválidas: {agent["name"]}')
        if set(agent['skills']) - names:
            issues.append(f'Skills inexistentes: {agent["name"]}')
        if set(agent['delegates']) - set(agent_names):
            issues.append(f'Delegados inexistentes: {agent["name"]}')
    return issues


def strip_block(text, begin=BEGIN, end=END):
    if begin not in text and end not in text:
        return text
    if text.count(begin) != 1 or text.count(end) != 1 or text.index(end) < text.index(begin):
        raise ValueError('Conflicto: bloque Mi.agents incompleto o duplicado')
    return re.sub(re.escape(begin) + r'.*?' + re.escape(end) + r'\r?\n?', '', text, flags=re.S)


def append_block(text, content, begin=BEGIN, end=END):
    base = strip_block(text, begin, end)
    # Do not grow whitespace on subsequent installs.
    return base.rstrip('\r\n') + ('\n\n' if base.strip() else '') + begin + '\n' + content.rstrip() + '\n' + end + '\n'


def skill_config(root, all_names, enabled):
    return ''.join('\n[[skills.config]]\npath = ' + quote((root / 'skills' / name / 'SKILL.md').as_posix()) + '\nenabled = ' + str(name in enabled).lower() + '\n' for name in all_names)


def set_mcp_enabled(text, name, enabled):
    if not re.fullmatch(r'[A-Za-z0-9_-]+', name) or name in ('node-repl', 'node_repl'):
        raise ValueError(f'MCP no gestionable: {name}')
    parsed = tomllib.loads(text)
    value = str(enabled).lower()
    if name not in parsed.get('mcp_servers', {}):
        return text.rstrip() + f'\n\n[mcp_servers.{name}]\nenabled = {value}\n'
    pattern = re.compile(r'(?m)^\[mcp_servers\.(?:' + re.escape(name) + '|' + re.escape(quote(name)) + r')\][ \t]*(?:#[^\r\n]*)?\r?$')
    found = pattern.search(text)
    if not found:
        raise ValueError(f'Conflicto: formato MCP {name}; use una tabla TOML explícita')
    next_table = re.search(r'(?m)^\s*\[', text[found.end():])
    stop = found.end() + next_table.start() if next_table else len(text)
    section = text[found.end():stop]
    setting = re.compile(r'(?m)^enabled\s*=.*$')
    if setting.search(section):
        section = setting.sub('enabled = ' + value, section)
    else:
        section = '\nenabled = ' + value + section
    result = text[:found.end()] + section + text[stop:]
    tomllib.loads(result)
    return result


def build_plan(root, home, project=None, profile='simple', managed_mcp=(), enabled_mcp=(), copilot=False):
    root, home = Path(root).resolve(), Path(home).resolve()
    project = Path(project).resolve() if project else None
    if profile not in PROFILES:
        raise ValueError('Perfil desconocido')
    if not project and profile != 'simple':
        raise ValueError('--profile development/security requiere --project; global usa invocación manual')
    issues = validate_library(root)
    if issues:
        raise ValueError('\n'.join(issues))
    if set(enabled_mcp) - set(managed_mcp):
        raise ValueError('--enable-mcp requiere también --manage-mcp')
    if enabled_mcp and not project:
        raise ValueError('--enable-mcp se reserva a un proyecto')
    agents = load_catalog(root)
    all_names = sorted(p.name for p in (root / 'skills').iterdir() if (p / 'SKILL.md').exists())
    common = read_text(root / 'instructions/common.md').replace('{{ROOT}}', root.as_posix())
    selected = set() if profile == 'simple' else set(next(a['skills'] for a in agents if a['name'] == ('cybersecurity' if profile == 'security' else 'development')))
    codex_dir = (project or home) / '.codex'
    oc_dir = project if project else home / '.config/opencode'
    plan = []

    def add(path, after, owned=False):
        check_path(path)
        before = read_bytes(path)
        if owned and before is not None and OWNER not in before.decode('utf-8-sig'):
            raise ValueError(f'Conflicto con archivo existente: {path}')
        plan.append({'path': str(path), 'before': before, 'after': after.encode('utf-8')})

    config_path = codex_dir / 'config.toml'
    base = strip_block(read_text(config_path))
    existing = tomllib.loads(base)
    content = ''
    if project:
        current_paths = {s['path'] for s in existing.get('skills', {}).get('config', [])}
        if any(str(root / 'skills' / n / 'SKILL.md').replace('\\', '/') in {p.replace('\\', '/') for p in current_paths} for n in all_names):
            raise ValueError('Conflicto con skills.config existente; combine la política manualmente')
        content += skill_config(root, all_names, selected)
    global_cfg = tomllib.loads(read_text(home / '.codex/config.toml'))
    for name in managed_mcp:
        if name not in global_cfg.get('mcp_servers', {}) and name not in existing.get('mcp_servers', {}):
            raise ValueError(f'MCP Codex no encontrado: {name}; no se inventan comandos ni credenciales')
        base = set_mcp_enabled(base, name, name in enabled_mcp)
    rendered = append_block(base, content)
    tomllib.loads(rendered)
    if project or managed_mcp:
        add(config_path, rendered)
    add(codex_dir / 'AGENTS.md' if not project else project / 'AGENTS.md', append_block(read_text(codex_dir / 'AGENTS.md' if not project else project / 'AGENTS.md'), common, MD_BEGIN, MD_END))

    oc_path = oc_dir / 'opencode.json'
    if (oc_dir / 'opencode.jsonc').exists():
        raise ValueError(f'JSONC existente: {oc_dir / "opencode.jsonc"}; conviértalo o integre manualmente para conservar comentarios')
    oc = json.loads(read_text(oc_path) or '{}')
    oc.setdefault('$schema', 'https://opencode.ai/config.json')
    oc.setdefault('default_agent', 'mi-simple')
    if not project:
        add(oc_dir / 'AGENTS.md', append_block(read_text(oc_dir / 'AGENTS.md'), common, MD_BEGIN, MD_END))
    if 'agent' in oc or 'permission' in oc:
        raise ValueError('Conflicto: configuración OpenCode V1 existente; migre a V2 antes de instalar')
    oc_agents = oc.setdefault('agents', {})
    for agent in agents:
        name = agent['name']
        native_oc_agent = (project / '.opencode/agents' if project else oc_dir / 'agents') / (name + '.md')
        if native_oc_agent.exists():
            raise ValueError(f'Conflicto con agente Markdown OpenCode existente: {native_oc_agent}')
        skill_paths = '\n'.join(f'- {s}: {(root / "skills" / s / "SKILL.md").as_posix()}' for s in agent['skills'])
        prompt = OWNER + '\n\n' + common + '\n' + read_text(root / 'agents' / agent['instructions']) + '\nSkills del rol (carga solo las necesarias por nombre o leyendo SKILL.md):\n' + skill_paths
        native = f'# {OWNER}\nname = {quote(name)}\ndescription = {quote(agent["description"])}\ndeveloper_instructions = {quote(prompt)}\nsandbox_mode = {quote("read-only" if agent["access"] == "read" else "workspace-write")}\n'
        model = agent.get('models', {}).get('codex')
        if model:
            native += f'model = {quote(model)}\n'
        effort = agent.get('reasoning_effort', {}).get('codex')
        if effort:
            native += f'model_reasoning_effort = {quote(effort)}\n'
        native += '\n[agents]\n' + ('enabled = false\n' if agent['access'] == 'read' else 'max_concurrent_threads_per_session = 3\n')
        native += skill_config(root, all_names, set(agent['skills']))
        tomllib.loads(native)
        add(codex_dir / 'agents' / (name + '.toml'), native, owned=True)
        if name in oc_agents and not oc_agents[name].get('system', '').startswith(OWNER):
            raise ValueError(f'Conflicto con agente OpenCode existente: {name}')
        def rule(action, resource, effect):
            return {'action': action, 'resource': resource, 'effect': effect}
        permission = [rule('skill', '*', 'deny')] + [rule('skill', s, 'allow') for s in agent['skills']]
        if agent['access'] == 'read':
            permission += [rule('edit', '*', 'deny'), rule('shell', '*', 'deny'), rule('subagent', '*', 'deny')]
        elif agent['access'] == 'report':
            permission += [rule('edit', '*', 'deny'), rule('edit', 'docs/security/**', 'allow'), rule('shell', '*', 'deny'), rule('subagent', '*', 'deny')]
            permission += [rule('subagent', n, 'allow') for n in agent['delegates']]
        else:
            permission += [rule('subagent', '*', 'ask')]
        oc_agents[name] = {'description': agent['description'], 'mode': agent['mode'], 'system': prompt, 'permissions': permission}
        if agent.get('models', {}).get('opencode'):
            oc_agents[name]['model'] = agent['models']['opencode']
        if copilot:
            cp_dir = project / '.github/agents' if project else home / '.copilot/agents'
            # Copilot frontmatter intentionally conservative: no invented tools or model IDs.
            cp = f'---\nname: {quote(name)}\ndescription: {quote(agent["description"])}\n---\n\n<!-- {OWNER} -->\n\n' + prompt
            add(cp_dir / (name + '.agent.md'), cp, owned=True)

    # Dedicated native simple role preserves the user's default agent and other permissions.
    if 'mi-simple' in oc_agents and not oc_agents['mi-simple'].get('system', '').startswith(OWNER):
        raise ValueError('Conflicto con agente OpenCode existente: mi-simple')
    oc_agents['mi-simple'] = {'description': 'Tareas directas, sin flujos automáticos.', 'mode': 'primary', 'system': OWNER + '\n' + common, 'permissions': [rule('subagent', '*', 'deny')]}
    if project:
        # Agent-specific permissions override this filter when the user explicitly selects a role.
        permissions = oc.setdefault('permissions', [])
        if not isinstance(permissions, list):
            raise ValueError('Conflicto con permissions existente; requiere integración manual')
        for name in all_names:
            permissions[:] = [r for r in permissions if not (r.get('action') == 'skill' and r.get('resource') == name)]
            permissions.append(rule('skill', name, 'allow' if name in selected else 'deny'))
    # OpenCode MCP names may differ; only touch explicitly named servers already defined there.
    global_oc = json.loads(read_text(home / '.config/opencode/opencode.json') or '{}')
    for name in managed_mcp:
        servers = oc.get('mcp', {}).get('servers', {})
        if project and name not in servers and name in global_oc.get('mcp', {}).get('servers', {}):
            raise ValueError(f'MCP OpenCode {name}: V2 requiere definición completa en el proyecto; agréguela con referencias a variables de entorno antes de cambiar disabled. No se copian credenciales globales.')
        if name in servers:
            servers[name]['disabled'] = name not in enabled_mcp
    add(oc_path, json.dumps(oc, ensure_ascii=False, indent=2) + '\n')
    return plan


def check_current(entries, key):
    for item in entries:
        check_path(Path(item['path']))
        if read_bytes(Path(item['path'])) != item[key]:
            raise ValueError(f'El archivo cambió; no se sobrescribe: {item["path"]}')


def write_value(path, value):
    check_path(path)
    if value is None:
        path.unlink(missing_ok=True)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.mi-agents-', delete=False) as output:
                temporary = Path(output.name)
                output.write(value)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)


def apply_plan(plan, state):
    check_current(plan, 'before')
    changed = [p for p in plan if p['before'] != p['after']]
    if not changed:
        return None
    state = Path(state)
    state.mkdir(parents=True, exist_ok=True)
    backup = state / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:8] + '.json')
    write_value(backup, json.dumps({'version': 1, 'files': [{'path': p['path'], 'before': base64.b64encode(p['before']).decode('ascii') if p['before'] is not None else None, 'after_sha256': digest(p['after'])} for p in changed]}, indent=2).encode('utf-8'))
    written = []
    try:
        for item in changed:
            check_current([item], 'before')
            write_value(Path(item['path']), item['after'])
            written.append(item)
    except Exception:
        for item in reversed(written):
            if read_bytes(Path(item['path'])) == item['after']:
                write_value(Path(item['path']), item['before'])
        raise
    return backup


def restore(backup):
    data = json.loads(read_text(Path(backup)))
    if data.get('version') != 1:
        raise ValueError('Backup no compatible')
    for item in data['files']:
        check_path(Path(item['path']))
        if digest(read_bytes(Path(item['path']))) != item['after_sha256']:
            raise ValueError(f'El archivo cambió después de instalar: {item["path"]}')
    plan = [{'path': item['path'], 'before': read_bytes(Path(item['path'])), 'after': base64.b64decode(item['before']) if item['before'] is not None else None} for item in reversed(data['files'])]
    written = []
    try:
        for item in plan:
            check_current([item], 'before')
            write_value(Path(item['path']), item['after'])
            written.append(item)
    except Exception:
        for item in reversed(written):
            if read_bytes(Path(item['path'])) == item['after']:
                write_value(Path(item['path']), item['before'])
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--home', type=Path, default=Path.home())
    parser.add_argument('--project', type=Path)
    parser.add_argument('--profile', choices=PROFILES, default='simple')
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--copilot', action='store_true')
    parser.add_argument('--validate', action='store_true')
    parser.add_argument('--restore', type=Path)
    parser.add_argument('--manage-mcp', action='append', default=[])
    parser.add_argument('--enable-mcp', action='append', default=[])
    args = parser.parse_args(argv)
    if args.validate:
        issues = validate_library(args.root)
        print('\n'.join(issues) if issues else 'Biblioteca válida: nombres, metadata y referencias.')
        return bool(issues)
    if args.restore:
        if not args.apply:
            print('Restauración requiere --apply. Backup:', args.restore)
            return 0
        restore(args.restore)
        print('Configuración restaurada.')
        return 0
    plan = build_plan(args.root, args.home, args.project, args.profile, args.manage_mcp, args.enable_mcp, args.copilot)
    for p in plan:
        print(('IGUAL   ' if p['before'] == p['after'] else 'CREAR   ' if p['before'] is None else 'ACTUALIZ') + ' ' + p['path'])
    if args.apply:
        backup = apply_plan(plan, args.root / '.local/backups')
        print('Backup:', backup if backup else 'sin cambios')
    else:
        print('Vista previa. No se escribió ningún archivo. Añada --apply para instalar.')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError) as error:
        print('ERROR:', error, file=sys.stderr)
        sys.exit(1)
