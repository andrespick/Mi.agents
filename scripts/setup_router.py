OWNER='Generated by Mi.agents OpenCode router; edit sources and reinstall.'
ROOT=Path(__file__).resolve().parents[1]
ROLES='architect sme researcher docs docs_design designer critic_sounding_board critic_drift_verifier critic_hallucination_verifier critic_architecture_supervisor curator_init curator_phase curator_postmortem curator_consolidation council_generalist council_skeptic council_domain_expert skill_improver spec_writer reviewer critic critic_oversight critic_finding_validator explorer coder test_engineer'.split()

def encode(value):return (json.dumps(value,ensure_ascii=False,indent=2)+'\n').encode('utf8')
def load(path):return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else {}
def sha(value):return hashlib.sha256(value).hexdigest() if value is not None else None
def check_path(path):
    for part in (path,*path.parents):
        try:info=part.lstat()
        except FileNotFoundError:continue
        if stat.S_ISLNK(info.st_mode) or getattr(info,'st_file_attributes',0)&0x400:
            raise ValueError(f'Destino enlazado: {part}')

def render_config(old,root):
    new=copy.deepcopy(old)
    agents=new.setdefault('agents',{})
    for name in ('mi-router','mi-worker','mi-answer'):
        if name in agents and OWNER not in agents[name].get('system',''):
            raise ValueError(f'Agente ajeno ya existe: {name}')
    deny=lambda action:{'action':action,'resource':'*','effect':'deny'}
    agents['mi-router']={'mode':'primary','description':'Entrada automática: clasifica con Luna none y selecciona el flujo.','model':'openai/gpt-6-luna#none','system':OWNER+'\nClasifica con router_route antes de trabajar.','permissions':[deny('edit'),deny('shell'),deny('subagent')]}
    agents['mi-router']['request']={'settings':{'transport':'http'},'body':{'tool_choice':{'type':'function','name':'router_route'},'parallel_tool_calls':False}}
    agents['mi-worker']={'mode':'all','description':'Cambios pequeños directos, Luna high.','model':'openai/gpt-6-luna#high','system':OWNER+'\nResuelve la tarea proporcionalmente; verifica cambios. Sin delegación.','permissions':[deny('subagent')]}
    agents['mi-answer']={'mode':'primary','description':'Preguntas e inspecciones directas.','model':'openai/gpt-6-luna#none','system':OWNER+'\nResponde e inspecciona en lectura, sin ceremonia SDD ni cambios.','permissions':[deny('edit'),deny('shell'),deny('subagent')]}
    plugins=[]
    target=(root/'opencode/router').as_posix()
    for plugin in new.get('plugins',[]):
        package=plugin if isinstance(plugin,str) else plugin.get('package','')
        if package=='opencode-swarm' or package.startswith('opencode-swarm@') or package.replace('\\','/').rstrip('/').endswith('/opencode/router'):continue
        plugins.append(plugin)
    new.update(default_agent='mi-router',model='openai/gpt-6-luna#none',plugins=[*plugins,target])
    return new

def render_swarm(old):
    new=copy.deepcopy(old)
    agents=new.setdefault('agents',{})
    for role in ROLES:
        agents[role]={**agents.get(role,{}),'model':'openai/gpt-6-luna' if role=='coder' else 'openai/gpt-6.1-sol','variant':'medium' if role=='test_engineer' else 'high','fallback_models':[]}
    new.update(auto_select_architect=False,max_iterations=8,qa_retry_limit=3,turbo_mode=False)
    new['guardrails']={**new.get('guardrails',{}),'max_coder_revisions':8,'max_concurrent_tasks':3}
    new['turbo']={**new.get('turbo',{}),'strategy':'lean','lean':{**new.get('turbo',{}).get('lean',{}),'max_parallel_coders':3,'require_declared_scope':True,'conflict_policy':'serialize','degrade_on_risk':True,'phase_reviewer':True,'phase_critic':True,'integrated_diff_required':True,'worktree_isolation':True,'allow_docs_only_without_reviewer':False}}
    return new

def plan_install(root,home,binding):
    config=home/'.config/opencode/opencode.json'
    swarm=home/'.config/opencode/opencode-swarm.json'
    local=root/'opencode/router/.local/binding.json'
    return {config:encode(render_config(load(config),root)),swarm:encode(render_swarm(load(swarm))),local:encode(binding)}

def write_atomic(path,data):
    check_path(path);path.parent.mkdir(parents=True,exist_ok=True)
    fd,tmp=tempfile.mkstemp(prefix='.router-',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as stream:stream.write(data);stream.flush();os.fsync(stream.fileno())
        os.replace(tmp,path)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)

def apply_plan(plan,backups):
    for path in plan:check_path(path)
    backup=backups/(datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+uuid.uuid4().hex[:8])
    backup.mkdir(parents=True)
    manifest=[]
    for path,data in plan.items():
        previous=path.read_bytes() if path.exists() else None
        manifest.append({'path':str(path),'before':base64.b64encode(previous).decode() if previous is not None else None,'after_sha256':sha(data)})
    write_atomic(backup/'manifest.json',encode(manifest))
    applied=[]
    try:
        for path,data in plan.items():write_atomic(path,data);applied.append(path)
    except Exception:
        for entry in reversed(manifest):
            path=Path(entry['path'])
            if path in applied:
                if entry['before'] is None:path.unlink(missing_ok=True)
                else:write_atomic(path,base64.b64decode(entry['before']))
        raise
    return backup

def restore(backup):
    entries=json.loads((backup/'manifest.json').read_text(encoding='utf8'))
    for entry in entries:
        path=Path(entry['path']);check_path(path)
        if sha(path.read_bytes() if path.exists() else None)!=entry['after_sha256']:
            raise ValueError(f'Cambios posteriores; no se sobrescribe: {path}')
    for entry in reversed(entries):
        path=Path(entry['path'])
        if entry['before'] is None:path.unlink(missing_ok=True)
        else:write_atomic(path,base64.b64decode(entry['before']))

def api(executable,operation,data=None):
    command=[str(executable),'api',operation]
    if data is not None:
        if operation=='credential.activate':command+=['--param','credentialID='+data['credentialID']]
        else:command+=['--data',json.dumps(data)]
    result=subprocess.run(command,capture_output=True,text=True,encoding='utf8',check=True,timeout=90)
    return json.loads(result.stdout) if result.stdout.strip() else None

def discover(executable,openai=None,anthropic=None):
    integrations=api(executable,'integration.list')['data']
    binding={}
    for provider,method,chosen,label in [('openai','oauth',openai,'OpenAI Cuenta'),('anthropic','key',anthropic,'Anthropic API')]:
        integration=next(i for i in integrations if i['id']==provider)
        candidates=[c for c in integration['connections'] if c['type']=='credential' and c['method']==method and (c['id']==chosen if chosen else c['label']==label)]
        if len(candidates)!=1:raise ValueError(f'Seleccione una credencial {provider}/{method} con --{provider}-credential')
        binding[provider]=candidates[0]['id']
    return binding

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--apply',action='store_true');p.add_argument('--root',type=Path,default=ROOT);p.add_argument('--home',type=Path,default=Path.home())
    p.add_argument('--opencode',type=Path,default=Path.home()/'AppData/Roaming/npm/node_modules/@opencode/cli/bin/opencode.exe')
    p.add_argument('--openai-credential');p.add_argument('--anthropic-credential');p.add_argument('--restore',type=Path)
    args=p.parse_args()
    if args.restore:
        if not args.apply:raise ValueError('Restaurar requiere --apply')
        restore(args.restore);print('Restaurado. Ejecute opencode reload.');return
    binding=discover(args.opencode,args.openai_credential,args.anthropic_credential)
    plan=plan_install(args.root,args.home,binding)
    print(json.dumps({'mode':'apply' if args.apply else 'dry-run','files':[str(f) for f in plan],'default_agent':'mi-router','openai':'pinned OAuth subscription only','anthropic':'Haiku only'},ensure_ascii=False,indent=2))
    if args.apply:
        if not (args.root/'opencode/router/node_modules/opencode-swarm/dist/index.js').is_file():raise ValueError('Primero ejecute npm ci --ignore-scripts dentro de opencode/router')
        # Select existing credentials; never request/print/store key or token values.
        for value in binding.values():api(args.opencode,'credential.activate',{'credentialID':value})
        backup=apply_plan(plan,args.root/'.local/router-backups')
        print(f'Backup: {backup}')
        subprocess.run([str(args.opencode),'reload'],check=True,timeout=90)

if __name__=='__main__':main()
